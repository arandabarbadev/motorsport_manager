// ============================================================
// MODELO DE DATOS BASE
// Estas interfaces son el contrato entre el motor de simulación,
// la IA de rivales y el render. No dependen de React ni de Canvas.
// ============================================================

// Spec 018: 'inter' is the intermediate rubber for light rain —
// faster than slicks on a damp track and than wets on a drying one.
export type TyreCompound = 'soft' | 'medium' | 'hard' | 'inter' | 'wet';
export type CarStatus = 'racing' | 'inPit' | 'dnf';
// Weekend event (spec 011): each calendar round is played as
// quali -> sprint1 -> sprint2 -> race, each one seeding the next grid.
export type WeekendEvent = 'quali' | 'sprint1' | 'sprint2' | 'race';
export type Weather = 'dry' | 'lightRain' | 'heavyRain';
// Race control flags: green (racing), yellow (slow, no fighting),
// red (race suspended).
export type RaceFlag = 'green' | 'yellow' | 'red';

// Spec 019: trainable pilot attributes (Pilotos tab). Each maps
// onto a real simulation stat — see PILOT_ATTRS in roster.ts.
export type PilotAttr = 'ritmo' | 'habilidad' | 'reflejos' | 'experiencia';

export interface Driver {
  id: string;
  name: string;
  // Race number: identifies the car without relying on team colors
  // (colorblind accessibility, spec 008). Player-editable 1-99 and
  // unique across the 20 drivers (spec 019).
  number: number;
  pace: number;
  consistency: number;
  aggression: number;
  wetSkill: number;
  riskTolerance: number;
  // Spec 019: experience lowers the incident risk in the sim
  // (see runIncidents). 50 = the pre-019 behavior (legacy saves
  // migrate to 50, so nothing changes for them).
  experience: number;
  // Spec 019: levels BOUGHT per attribute (cost scaling only; the
  // live stat is the stat itself). Player team only.
  training?: Partial<Record<PilotAttr, number>>;
}

export interface Car {
  id: string;
  teamId: string;
  aero: number;
  engine: number;
  chassis: number;
  reliability: number;
}

export interface Team {
  id: string;
  name: string;
  budget: number;
  color: string;
}

export interface TyreState {
  compound: TyreCompound;
  wear: number;
  lapsOnTyre: number;
}

export interface Track {
  id: string;
  name: string;
  totalLaps: number;
  path: { x: number; y: number }[];
  overtakeDifficulty: number;
  tyreDegradationFactor: number;
  pitLaneTimeLoss: number;
}

export interface RaceCarState {
  driverId: string;
  carId: string;
  teamId: string;
  lapProgress: number;
  currentLap: number;
  tyre: TyreState;
  fuel: number;
  gapToLeaderSec: number;
  position: number;
  pitStopsCompleted: number;
  status: CarStatus;
  isPlayerControlled: boolean;
  // Engine extension: simulated seconds of pit time still remaining
  // while status is 'inPit' (0 when racing).
  pitTimerSec: number;
  // Engine extension: pit stop duration override in seconds (used by
  // the player's cars when the mechanics staff level reduces the
  // stop time). Falls back to track.pitLaneTimeLoss.
  pitLaneTimeOverrideSec?: number;
}

export interface RaceState {
  track: Track;
  weather: Weather;
  cars: RaceCarState[];
  // Engine extension: team lookup by id (team colors for the renderer/HUD).
  teams: Team[];
  // Engine extension: roster lookup by id, so simulationTick can resolve
  // real Driver stats and Car ratings for every RaceCarState.
  drivers: Driver[];
  carSpecs: Car[];
  currentTick: number;
  simTimeMultiplier: 1 | 5 | 10 | 20;
  isPaused: boolean;
  // Engine extension: race control flag state (accidents/weather).
  flag: RaceFlag;
  // Simulated seconds remaining for the current yellow/red flag.
  flagTimerSec: number;
  // Engine extension (Phase 7): events produced by THIS tick
  // (overtakes, pit entries). Replaced every tick.
  raceEvents: RaceEvent[];
  // Engine extension: false = this race stays dry from start to finish
  // (rain is a per-race lottery, not every race).
  weatherCanChange: boolean;
}

export interface PitCommand {
  carDriverId: string;
  newCompound: TyreCompound;
  requestedAtTick: number;
}

// Race events generated by the engine each tick (Phase 7): the
// render layer reads them for visual feedback and they are
// replaced on the next tick.
export interface RaceEvent {
  type: 'overtake' | 'pitEntry' | 'incident';
  carDriverId: string;
  previousPosition?: number;
  newPosition?: number;
  // Only on 'incident' (spec 012): what happened to the car.
  incidentKind?: 'spin' | 'crash' | 'mechanical';
}
